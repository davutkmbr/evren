export interface MaterialRecord {
  id: string;
  baseColorFactor: [number, number, number, number];
  baseColor: string | null;
  normal: string | null;
  orm: string | null;
  tiling: [number, number];
  roughness: number;
  metallic: number;
  alphaMode: 'OPAQUE' | 'MASK';
  doubleSided: boolean;
  tinted: boolean;
}

const r4 = (v: number): number => Math.round(v * 10000) / 10000;
const toLinear = (c: number): number => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));

/** Mean linear RGB of an sRGB image (sampled on a 128 px thumbnail). */
async function meanLinear(file: string): Promise<[number, number, number]> {
  const { data, info } = await sharp(file).resize(128, 128, { fit: 'fill' }).removeAlpha().raw().toBuffer({ resolveWithObject: true });
  const sum = [0, 0, 0];
  const lut = Array.from({ length: 256 }, (_, i) => toLinear(i / 255));
  for (let i = 0; i < data.length; i += info.channels) {
    sum[0] += lut[data[i]];
    sum[1] += lut[data[i + 1]];
    sum[2] += lut[data[i + 2]];
  }
  const n = data.length / info.channels;
  return [sum[0] / n, sum[1] / n, sum[2] / n];
}

/**
 * Bakes the textures of the used materials into <out>/textures/ and returns their records (only `used` ids, in
 * table order).
 */
export async function materialRecords(outDir: string, used: ReadonlySet<string>, extra: readonly LandmarkMaterial[] = []): Promise<MaterialRecord[]> {
  const all = [...LANDMARK_MATERIALS, ...extra].filter((m) => used.has(m.id));
  defineMaterials(all.filter((m) => m.textures).map((m) => ({ id: m.id, color: 0xffffff, textures: m.textures, tiling: m.tiling, alphaMode: m.alphaMode, replace: true })));
  const baker = bakerFor(outDir);
  const out: MaterialRecord[] = [];
  for (const m of all) {
    let baseColor: string | null = null;
    let normal: string | null = null;
    let orm: string | null = null;
    let factor: [number, number, number] = m.color ?? [1, 1, 1];
    if (m.textures) {
      const set = await baker.material(m.id);
      if (!set) {
        throw new Error(`${m.id}: texture set unavailable (${[...baker.problems].map(([k, v]) => `${k}: ${v}`).join('; ')})`);
      }
      baseColor = set.baseColor ? `textures/${set.baseColor.file}` : null;
      normal = set.normal ? `textures/${set.normal.file}` : null;
      orm = set.orm ? `textures/${set.orm.file}` : null;
      if (m.tinted && baseColor) {
        const mean = await meanLinear(join(outDir, baseColor));
        factor = [factor[0] / mean[0], factor[1] / mean[1], factor[2] / mean[2]];
      }
    } else if (m.generated) {
      mkdirSync(join(outDir, 'textures'), { recursive: true });
      const put = (file: string | undefined): string | null => {
        if (!file) return null;
        const dst = join(outDir, 'textures', basename(file));
        if (!existsSync(dst)) copyFileSync(file, dst);
        return `textures/${basename(file)}`;
      };
      baseColor = put(m.generated.baseColor);
      normal = put(m.generated.normal);
      orm = put(m.generated.orm);
      factor = [factor[0] / m.generated.scale, factor[1] / m.generated.scale, factor[2] / m.generated.scale];
    }
    out.push({
      id: m.id,
      baseColorFactor: [r4(factor[0]), r4(factor[1]), r4(factor[2]), 1],
      baseColor,
      normal,
      orm,
      tiling: m.tiling ?? [2, 2],
      roughness: m.roughness,
      metallic: m.metallic ?? 0,
      alphaMode: m.alphaMode ?? 'OPAQUE',
      doubleSided: m.doubleSided ?? false,
      tinted: m.tinted,
    });
  }
  return out;
}

/** Whether a material takes its colour from COLOR_0. */
export function isTinted(id: string, extra: readonly LandmarkMaterial[] = []): boolean {
  return ([...LANDMARK_MATERIALS, ...extra].find((m) => m.id === id) ?? { tinted: true }).tinted;
}

const bakers = new Map<string, TextureBaker>();
function bakerFor(outDir: string): TextureBaker {
  let b = bakers.get(outDir);
  if (!b) {
    b = new TextureBaker(outDir);
    bakers.set(outDir, b);
  }
  return b;
}

/** Bakes one approved set (as the street tiles do) and returns its files, for the composites (composite.ts). */
export async function bakeSet(outDir: string, id: string, textures: TextureSetRef, tiling: [number, number]): Promise<{ color: string; normal?: string; orm?: string; tiling: [number, number] }> {
  defineMaterials([{ id, color: 0xffffff, textures, tiling, replace: true }]);
  const set = await bakerFor(outDir).material(id);
  if (!set?.baseColor) {
    throw new Error(`${id}: texture set unavailable`);
  }
  const at = (f?: { file: string }): string | undefined => (f ? join(outDir, 'textures', f.file) : undefined);
  return { color: at(set.baseColor)!, normal: at(set.normal), orm: at(set.orm), tiling };
}
