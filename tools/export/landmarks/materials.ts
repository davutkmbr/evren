/**
 * The landmark materials of the export: one shared set (`lm_*`) for every landmark family, written as material
 * definitions in the manifest's `materialDefs` (the world compiler's shape, read by the Unreal importer's
 * evren_surfaces.py: baseColorFactor, baseColor / normal / orm files, tiling in metres, roughness, metallic, alphaMode).
 *
 * The web shades landmarks with procedural shaders; here every surface gets an approved texture set (the world
 * compiler's TextureBaker, so files are named and processed exactly as the street tiles' and Unreal imports each once)
 * or a flat PBR colour.
 *
 * Colour: `tinted` materials take their colour from COLOR_0 (the builders' per-vertex tint, times ambient occlusion);
 * their texture only adds relative detail, so the baseColorFactor divides it by its mean linear colour. The other
 * materials keep the texture's own colour (brick, roof tiles, asphalt) or a flat colour; COLOR_0 then carries only AO.
 */
import { copyFileSync, existsSync, mkdirSync } from 'node:fs';
import { basename, join } from 'node:path';
import sharp from 'sharp';
import { defineMaterials, type TextureSetRef } from '../../world-compiler/src/materials';
import { TextureBaker } from '../../world-compiler/src/textures';

export interface LandmarkMaterial {
  id: string;
  /** Approved texture set (world compiler registry form). */
  textures?: TextureSetRef;
  /** A texture generated by the exporter (composite.ts) instead of a set. */
  generated?: GeneratedSet;
  /** Metres per texture repeat. */
  tiling?: [number, number];
  /** Linear colour: flat colour, or the factor on the texture (untinted), or a multiplier (tinted). */
  color?: [number, number, number];
  tinted: boolean;
  roughness: number;
  metallic?: number;
  alphaMode?: 'OPAQUE' | 'MASK';
  doubleSided?: boolean;
}

export interface GeneratedSet {
  baseColor: string;
  normal?: string;
  orm?: string;
  /** The base colour stores colour x this (so values above 1 fit into 8 bits); the factor divides it out. */
  scale: number;
}

